type Gsap = typeof import("gsap")["gsap"];

/**
 * A coreografia. Tempos em segundos a partir do início da timeline.
 *
 *  0.00  cena parada: letreiro sem o G, G pendurado acima (fora da caixa — o svg
 *        tem overflow visível, então ele desce de fora da tela), pinguim fora à esquerda
 *  0.20  o pinguim entra andando (relógio do gingado começa)
 *  1.30  o G começa a descer torto, como coisa pendurada: balança, não se endireita
 *  1.70  o pinguim olha para cima, acompanhando o G
 *  2.20  o pinguim freia: a amplitude do gingado vai a zero e a nadadeira sobe
 *  2.95  a nadadeira chega à posição, um instante antes do G — ela guia
 *  3.05  o toque endireita o G: passa 0,5° do prumo e assenta a 0° — que agora é
 *        vertical de verdade (o G do cartão pendia 1,07° e foi corrigido nas
 *        máscaras). Junto, afunda 3px e volta: recebe o peso. O pinguim se
 *        inclina, GARRIDO se acomoda, a cabeça volta
 */
function montarCena(gsap: Gsap, svg: SVGSVGElement, aoPronta?: (c: Cena) => void) {
  const q = (s: string) => svg.querySelector<SVGGElement>(s)!;
  const G = q('[data-cena="g"]'), garrido = q('[data-cena="garrido"]');
  const gingado = criarGingado(svg, { pernaF: 6 });
  const px = { t: 0, env: 1, x: -290, incl: 0, olhar: 0 };
  const pintar = () => gingado.aplicar(px.t, px.env, px.x, 0, px.incl, px.olhar);

  gsap.set(G, { y: -230, rotation: -6, transformOrigin: "50% 100%" });
  gsap.set(garrido, { y: 0 });
  pintar();

  const tl = gsap.timeline({ paused: true, onUpdate: pintar });
  tl.to(px, { t: 2.85, duration: 2.85, ease: "none" }, 0.2)                       // relógio do gingado
    .to(px, { x: -34, duration: 2.05, ease: "none" }, 0.2)                        // caminhada
    .to(px, { x: 0, duration: 0.75, ease: "power2.out" }, 2.2)                    // freio
    .to(px, { env: 0, duration: 0.75, ease: "power1.inOut" }, 2.2)                // amplitude some, nadadeira sobe (chega a 0 em 2.95)
    // o pinguim olha para cima enquanto o G desce, e volta ao encaixar
    .to(px, { olhar: -3.5, duration: 0.6, ease: "power2.out" }, 1.7)
    .to(px, { olhar: 0, duration: 0.4, ease: "power2.inOut" }, 3.0)
    // o G desce torto, como coisa pendurada: balança, mas NÃO endireita sozinho
    .to(G, { y: 0, duration: 1.75, ease: "power2.inOut" }, 1.3)
    .to(G, { rotation: -2.6, duration: 0.7, ease: "sine.inOut" }, 1.3)
    .to(G, { rotation: -4.4, duration: 0.55, ease: "sine.inOut" }, 2.0)
    .to(G, { rotation: -3.2, duration: 0.5, ease: "sine.inOut" }, 2.55)
    // contato em 3.05: o toque da nadadeira endireita o G — passa 0.5° do prumo e assenta.
    // Junto, ele afunda 3px e volta, recebendo o peso.
    .to(G, { rotation: 0.5, duration: 0.2, ease: "power2.out" }, 3.05)
    .to(G, { rotation: 0, duration: 0.18, ease: "power2.inOut" }, 3.25)
    .to(G, { y: 3, scaleY: 0.993, duration: 0.09, ease: "power2.out" }, 3.05)
    .to(G, { y: 0, scaleY: 1, duration: 0.2, ease: "power2.inOut" }, 3.14)
    .to(px, { incl: 1.2, duration: 0.12, ease: "power2.out" }, 3.05)
    .to(px, { incl: 0, duration: 0.26, ease: "power2.inOut" }, 3.17)
    .to(garrido, { y: 2, duration: 0.1, ease: "power2.out" }, 3.07)
    .to(garrido, { y: 0, duration: 0.2, ease: "power2.inOut" }, 3.17);

  // play antes de entregar o controle: quem chamar progress() pausa por cima.
  tl.play();
  aoPronta?.({
    progress: (p) => { tl.pause(); tl.progress(p); pintar(); },
    play: () => tl.play(),
    pause: () => tl.pause(),
    paused: () => tl.paused(),
    restart: () => tl.restart(),
    duration: () => tl.duration(),
  });
  return () => { tl.kill(); gingado.repouso(); };
}
